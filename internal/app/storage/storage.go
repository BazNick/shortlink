package storage

// Storage определяет интерфейс операций хранения сокращённых ссылок.
// Реализации этого интерфейса предоставляют методы для сохранения и извлечения
// сопоставлений адресов в различных хранилищах (in-memory, файлs, база данных)
type Storage interface {
	// Добавляет новое отображение хэша на ссылку.
	//
	// Параметры:
	//   - hash: короткий хэш адреса
	//   - link: исходная ссылка
	//   - userID: идентификатор пользователя
	//
	// Возвращает:
	//   - string: возвращает пустую строку
	//   - error: любая ошибка, возникшая при сохранении
	AddHash(hash, link, userID string) (string, error)

	// Получает оригинальную ссылку, ассоциированную с данным хэшем.
	//
	// Параметры:
	//   - hash: короткий хэш адреса для поиска
	//
	// Возвращает:
	//   - string: оригинальная ссылка, если найдена, иначе пустая строка
	GetHash(hash string) string

	// Проверяет наличие заданной оригинальной ссылки в хранилище.
	//
	// Параметры:
	//   - link: оригинальная ссылка для проверки
	//
	// Возвращает:
	//   - bool: true, если ссылка существует, false — в противном случае
	CheckValExists(link string) bool
}
